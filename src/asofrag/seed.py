"""Generate the synthetic handbook editions, the 60-question set and the fault plan.

Everything is derived from the catalog in ``seeddata`` and a seeded ``random.Random``, so the same
seed always writes byte-identical files. Gold answers come from the clause-version timeline built
by diffing the written editions, not from the catalog directly.
"""

from __future__ import annotations

import random
from datetime import date, timedelta
from pathlib import Path

import yaml

from .corpus import load_handbooks
from .seeddata import (
    BEFORE_AND_AFTER,
    BEFORE_TWICE,
    CATALOG,
    EDITIONS,
    FABRICATED_QUOTES,
    HORIZON_END,
    INTRODUCED_ASKED,
    REPEALED_ASKED,
    SECTIONS,
    UNCHANGED_ASKED,
    V1,
    Spec,
)
from .textutil import split_sentences
from .timeline import Timeline, build_timeline

DEFAULT_SEED = 7
_SPECS = {s.clause_id: s for s in CATALOG}


def render_edition(when: date) -> str:
    """Markdown for the handbook edition effective on ``when``."""
    lines = [
        "# Employee Handbook",
        "",
        f"Edition effective {when.isoformat()}. Synthetic data generated by `asofrag seed`.",
        "",
    ]
    for number, (key, name) in enumerate(SECTIONS.items(), start=1):
        lines += [f"## {number}. {name}", ""]
        here = [s for s in CATALOG if s.exists_at(when) and s.section_at(when) == key]
        # clauses that moved in from another section go after the section's own clauses
        here.sort(key=lambda s: s.section != key)
        for spec in here:
            lines += [f"### {spec.title} {{#{spec.clause_id}}}", "", spec.render(when), ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def _pick(rng: random.Random, start: date, end: date) -> date:
    return start + timedelta(days=rng.randrange((end - start).days + 1))


def _with_date(rng: random.Random, question: str, when: date) -> str:
    """Embed the as-of date in the question, in one of three styles."""
    style = rng.randrange(3)
    dmy = f"{when.day} {when:%B} {when.year}"
    lowered = question[0].lower() + question[1:]
    if style == 0:
        return f"On {dmy}, {lowered}"
    if style == 1:
        return f"As of {when.isoformat()}, {lowered}"
    return f"{question} (as of {dmy})"


def _plan(rng: random.Random) -> list[tuple[str, Spec, int, date]]:
    """(category, spec, phrasing index, as-of date) for the 60 questions, before shuffling."""
    plan: list[tuple[str, Spec, int, date]] = []

    def before(spec: Spec, phrasing: int, pinned: bool = False) -> None:
        assert spec.change is not None
        when = spec.pin if pinned and spec.pin else _pick(rng, V1, spec.change - timedelta(days=1))
        plan.append(("before_change", spec, phrasing, when))

    def after(spec: Spec, phrasing: int) -> None:
        assert spec.change is not None
        plan.append(("after_change", spec, phrasing, _pick(rng, spec.change, HORIZON_END)))

    for cid in BEFORE_TWICE:
        before(_SPECS[cid], 0, pinned=True)
        before(_SPECS[cid], 1)
    for cid in BEFORE_AND_AFTER:
        spec = _SPECS[cid]
        before(spec, 0)
        after(spec, 0)
        after(spec, 1)
    for cid in UNCHANGED_ASKED:
        spec = _SPECS[cid]
        plan.append(("unchanged", spec, 0, _pick(rng, V1, HORIZON_END)))
    for cid, n in REPEALED_ASKED.items():
        spec = _SPECS[cid]
        for i in range(n):
            assert spec.repeal is not None
            plan.append(("repealed", spec, i, _pick(rng, spec.repeal, HORIZON_END)))
    for cid, n in INTRODUCED_ASKED.items():
        spec = _SPECS[cid]
        for i in range(n):
            plan.append(("not_yet_introduced", spec, i, _pick(rng, V1, spec.intro - timedelta(1))))
    return plan


def build_questions(timeline: Timeline, rng: random.Random) -> list[dict]:
    rows = []
    for category, spec, phrasing, when in _plan(rng):
        text = _with_date(rng, spec.questions[phrasing], when)
        if category in ("repealed", "not_yet_introduced"):
            if timeline.in_force(when) and any(
                v.clause_id == spec.clause_id for v in timeline.in_force(when)
            ):
                raise AssertionError(f"{spec.clause_id} unexpectedly in force on {when}")
            gold, value = "abstain", None
        else:
            live = [v for v in timeline.in_force(when) if v.clause_id == spec.clause_id]
            if len(live) != 1:
                raise AssertionError(f"{spec.clause_id}: {len(live)} versions in force on {when}")
            gold = live[0].key
            value = spec.gold_value(live[0].effective_from)
        rows.append(
            {
                "category": category,
                "question": text,
                "as_of": when.isoformat(),
                "gold": gold,
                "gold_value": value,
            }
        )
    rng.shuffle(rows)
    return [{"id": f"Q{i:02d}", **row} for i, row in enumerate(rows, start=1)]


def build_faults(questions: list[dict], timeline: Timeline) -> list[dict]:
    """Seven first-attempt failures: 2 superseded citations, 3 fabricated quotes and 2 citations
    of a clause that was not retrieved."""
    by_cat: dict[str, list[dict]] = {}
    for q in questions:
        by_cat.setdefault(q["category"], []).append(q)
    after = by_cat["after_change"][:2]
    unchanged = by_cat["unchanged"][:5]
    asked = set(BEFORE_TWICE) | set(BEFORE_AND_AFTER) | set(UNCHANGED_ASKED)
    fillers = [
        s
        for s in CATALOG
        if not s.change and not s.repeal and s.intro == V1 and s.clause_id not in asked
    ]
    faults: list[dict] = []

    for q in after:
        clause_id = q["gold"].split("@")[0]
        old = timeline.versions_of(clause_id)[0]
        faults.append(
            {
                "question": q["id"],
                "attempt": 1,
                "kind": "superseded_citation",
                "expect": "CITATION_OUT_OF_FORCE",
                "citation": {
                    "clause_id": clause_id,
                    "version": old.version,
                    "quote": split_sentences(old.text)[0],
                },
            }
        )
    for q, fake in zip(unchanged[:3], FABRICATED_QUOTES, strict=True):
        clause_id, version = q["gold"].split("@")
        faults.append(
            {
                "question": q["id"],
                "attempt": 1,
                "kind": "fabricated_quote",
                "expect": "QUOTE_NOT_FOUND",
                "citation": {"clause_id": clause_id, "version": version, "quote": fake},
            }
        )
    used: set[str] = set()
    for q in unchanged[3:5]:
        section = _SPECS[q["gold"].split("@")[0]].section
        target = next(s for s in fillers if s.section != section and s.clause_id not in used)
        used.add(target.clause_id)
        version = timeline.versions_of(target.clause_id)[0]
        faults.append(
            {
                "question": q["id"],
                "attempt": 1,
                "kind": "unretrieved_citation",
                "expect": "CITATION_NOT_RETRIEVED",
                "citation": {
                    "clause_id": target.clause_id,
                    "version": version.version,
                    "quote": split_sentences(version.text)[0],
                },
            }
        )
    return faults


def _dump(data: dict, header: str) -> str:
    body = yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=10_000)
    return f"# {header}\n{body}"


def write_seed(out: str | Path = ".", seed: int = DEFAULT_SEED) -> dict[str, int]:
    """Write ``handbook/``, ``evals/questions.yaml`` and ``evals/faults.yaml`` under ``out``."""
    root = Path(out)
    (root / "handbook").mkdir(parents=True, exist_ok=True)
    (root / "evals").mkdir(parents=True, exist_ok=True)
    for when in EDITIONS:
        text = render_edition(when)
        (root / "handbook" / f"v{when.isoformat()}.md").write_text(text, encoding="utf-8")

    timeline = build_timeline(load_handbooks(root / "handbook"))
    rng = random.Random(seed)
    questions = build_questions(timeline, rng)
    faults = build_faults(questions, timeline)
    header = f"Synthetic data generated by `asofrag seed --seed {seed}`."
    (root / "evals" / "questions.yaml").write_text(
        _dump({"questions": questions}, header), encoding="utf-8"
    )
    (root / "evals" / "faults.yaml").write_text(_dump({"faults": faults}, header), encoding="utf-8")
    return {"editions": len(EDITIONS), "questions": len(questions), "faults": len(faults)}
